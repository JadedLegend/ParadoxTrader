import type { InquiryMetadata, LineageDetailResponse, LineageFixture, LineageListResponse } from './contracts'

const MAX_OFFSET = 2 ** 31 - 1
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const CATEGORIES = ['entries', 'proposals', 'orders', 'fills', 'positions', 'reviews', 'events'] as const
const invalid = () => new Error('Invalid local lineage request. No backend fallback was attempted.')
function integer(params: URLSearchParams, field: string, fallback: number, min: number, max: number) {
  const value = params.get(field)
  if (value === null) return fallback
  if (value.length > 10 || !/^[0-9]+$/.test(value)) throw invalid()
  const number = Number(value)
  if (!Number.isSafeInteger(number) || number < min || number > max) throw invalid()
  return number
}
function metadata(value: InquiryMetadata): InquiryMetadata {
  // Only explicit owner metadata belongs in the list, never detail or memory text.
  return { inquiry_id: value.inquiry_id, agent_id: value.agent_id, title: value.title,
    state: value.state, phase: value.phase, visibility: value.visibility,
    created_at: value.created_at, updated_at: value.updated_at }
}

/** Two local read routes only. The engine-generated example is loaded on demand. */
export async function readLineageFixture(path: string): Promise<LineageListResponse | LineageDetailResponse> {
  if (typeof path !== 'string' || path.length > 512 || !path.startsWith('/api/lineage/')) throw invalid()
  const url = new URL(path, 'https://local.invalid')
  const listRoute = url.pathname === '/api/lineage/inquiries'
  const match = /^\/api\/lineage\/inquiries\/([^/]+)$/.exec(url.pathname)
  if (url.hash || (!listRoute && !match)) throw invalid()
  const allowed = listRoute ? ['agent_id', 'limit', 'offset'] : ['agent_id']
  for (const key of url.searchParams.keys()) {
    if (!allowed.includes(key) || url.searchParams.getAll(key).length !== 1) throw invalid()
  }
  if ((url.searchParams.get('agent_id') ?? 'alchemist') !== 'alchemist') {
    throw new Error('Lineage pilot agent not found.')
  }
  const id = match?.[1]
  if (id && !UUID.test(id)) throw invalid()
  const limit = listRoute ? integer(url.searchParams, 'limit', 50, 1, 50) : 50
  const offset = listRoute ? integer(url.searchParams, 'offset', 0, 0, MAX_OFFSET) : 0
  // Generated by scripts/build_lineage_fixture.py; no handwritten replacement.
  const fixture = (await import('./fixture.json')).default as unknown as LineageFixture
  if (fixture.mode !== 'mock_demo' || fixture.agent_id !== 'alchemist' || fixture.list.status !== 'ok') {
    throw new Error('Local lineage example unavailable.')
  }
  if (fixture.list.inquiries.some(inquiry => inquiry.agent_id !== 'alchemist')) {
    throw new Error('Local lineage example unavailable.')
  }
  if (listRoute) {
    const items = fixture.list.inquiries
    return structuredClone({ status: 'ok', inquiries: items.slice(offset, offset + limit).map(metadata),
      total: fixture.list.total, limit, offset,
      truncated: Boolean(fixture.list.truncated || fixture.list.offset !== 0 || items.length < fixture.list.total) })
  }
  const detail = id && Object.hasOwn(fixture.details, id) ? fixture.details[id] : undefined
  if (!detail || detail.inquiry.agent_id !== 'alchemist' || detail.inquiry.inquiry_id !== id) {
    throw new Error('Lineage inquiry not found.')
  }
  for (const category of CATEGORIES) {
    if (!Array.isArray(detail[category]) || detail[category].some(record => record.agent_id !== undefined && record.agent_id !== 'alchemist')) {
      throw new Error('Local lineage example unavailable.')
    }
  }
  const result = structuredClone(detail)
  result.inquiry = metadata(detail.inquiry)
  result.truncated = Boolean(detail.truncated || CATEGORIES.some(category => detail[category].length > 100))
  // Keep each typed array bounded without collapsing missing and unavailable states.
  result.entries = result.entries.slice(0, 100)
  result.proposals = result.proposals.slice(0, 100)
  result.orders = result.orders.slice(0, 100)
  result.fills = result.fills.slice(0, 100)
  result.positions = result.positions.slice(0, 100)
  result.reviews = result.reviews.slice(0, 100)
  result.events = result.events.slice(0, 100)
  return result
}
